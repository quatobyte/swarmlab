const advise = (kind, blocks) => (blocks ? ERRORS_RU[kind] : ERRORS_PY[kind] || ERRORS_RU[kind]);

const fill = (text, map) => text.replace(/\{(\w+)\}/g, (_, k) => (k in map ? map[k] : `{${k}}`));

/** Чья программа: из заголовка ошибки хоста пчёл («Ошибка: Пчела forager id=0, тик 5…»). */
export function whoOf(title) {
  const t = String(title || "");
  let m = /Пчела (\w+) id=(\d+)/.exec(t);
  if (m) return `${LOG_RU.who[m[1]] || LOG_RU.who.bee} #${m[2]}`;
  m = /пчелы id=(\d+)/.exec(t);
  if (m) return `${LOG_RU.who.bee} #${m[1]}`;
  if (/Улей|улья/.test(t)) return LOG_RU.who.hive;
  if (/не загрузился/.test(t)) return LOG_RU.who.load;
  return "";
}

/**
 * Запись об ошибке → слова. `blocks` — программа из блоков: показываем пояснение вместо текста
 * Python. Возвращает {who, text, detail}: «кто», главное и (для Python) совет второй строкой.
 */
export function describeError({ title = "", message = "" }, { blocks = false } = {}) {
  const who = whoOf(title);
  const kind = errorKind(message || title);
  const advice = kind === "other" ? null : advise(kind, blocks);
  if (!message) return { who, text: advice || LOG_RU.stopped, detail: null };
  if (blocks) return { who, text: advice || message.replace(/^[\w.]+:\s*/, ""), detail: null };
  return { who, text: message, detail: advice };
}

/** «Та же ошибка (TypeError, строка 15) уже 10 раз. Последний: Пчела forager id=3, тик 120». */
export function describeRepeat(text) {
  const m = /^Та же ошибка \(([\w.]+), строка (\d+)\) уже (\d+) раз\. Последний: (.*)$/.exec(String(text));
  if (!m) return null;
  return { who: whoOf(m[4]), line: Number(m[2]), text: fill(LOG_RU.repeat, { n: m[3] }) };
}

/**
 * Строка ядра или сервера («[ядро] …», «[сервер] …») → {level: "warn" | "err", text} простыми
 * словами или `null` — служебная, игроку не показываем. Не строка ядра — `undefined`.
 * `blocks` — открыта программа из блоков: совет словами блоков.
 */
export function describeCore(text, { blocks = false } = {}) {
  const m = /^\[(ядро|сервер|stderr)\]\s*(.*)$/s.exec(String(text));
  if (!m) return undefined;
  if (m[1] === "stderr") return null; // падение самого раннера: подробности — в logs/
  const rest = m[2];
  if (/^запуск раннера|^скрипт не загрузился:?$/.test(rest)) return null; // ошибка загрузки — следом
  let n = /и ещё (\d+) строк/.exec(rest);
  if (n) return { level: "warn", text: fill(LOG_RU.more, { n: n[1] }) };
  n = /\((\d+) подряд/.exec(rest);
  if (/пропущен: раннер не работает/.test(rest)) return { level: "warn", text: LOG_RU.dead };
  if (/пропущен/.test(rest)) return { level: "warn", text: fill(LOG_RU.skipped, { n: n ? n[1] : 1 }) };
  n = /превышений: (\d+)/.exec(rest);
  if (n) return { level: "warn", text: fill(LOG_RU.budget, { advice: advise("budget", blocks), n: n[1] }) };
  const kind = errorKind(rest);
  if (kind === "crash") return { level: "err", text: LOG_RU.crash };
  return { level: kind === "disabled" ? "err" : "warn", text: kind === "other" ? rest : advise(kind, blocks) };
}
