#  ---------------------------------------------------------------------
#  ЧТО ТАКОЕ ТИК
#  ---------------------------------------------------------------------
#  Игра идёт маленькими шагами — тиками. Тиков 10 в секунду.
#  Каждый тик у КАЖДОЙ пчелы вызывается метод step(). В нём пчела смотрит
#  вокруг (сенсоры) и решает, что делать (команды).
#  Пчела помнит только то, что ты сам сохранишь в self:
#      self.my_flower = flower      # запомнили
#      ... на следующем тике self.my_flower всё ещё здесь
#
#  ---------------------------------------------------------------------
#  ЧТО ВИДИТ ПЧЕЛА (s — это Sensors)
#  ---------------------------------------------------------------------
#  s.me.pos            где я (s.me.pos.x, s.me.pos.y, s.me.pos.z), метры
#  s.me.energy_percent сколько энергии осталось, 0–100. На нуле пчела падает!
#  s.me.cargo          сколько нектара несу (сборщик носит до 1.5)
#  s.me.is_full        True, если груз полный
#  s.me.in_hive        True, если я внутри улья
#  s.home.pos          где вход в мой улей (леток); s.home.dist — далеко ли
#  s.flowers           цветы рядом. У цветка: .id, .pos, .dist, .nectar
#  s.nearest_flower()  ближайший цветок (или None, если не видно)
#  s.bees              пчёлы рядом (.friend — своя ли)
#  s.enemies           враги рядом (шершни), s.nearest_enemy()
#  s.messages          сообщения от своих пчёл (.values — числа)
#  s.time              сколько секунд идёт матч
#  Видно только то, что близко! Разведчик видит на 25 м, сборщик — на 8 м.
#
#  ---------------------------------------------------------------------
#  КАКИЕ ЕСТЬ КОМАНДЫ
#  ---------------------------------------------------------------------
#  self.fly_to(x, y)        лететь к точке (высоту автопилот держит сам)
#  self.fly_dir(dx, dy)     лететь в направлении
#  self.hover()             висеть на месте
#  self.go_home()           домой, в улей (там заправка энергией)
#  self.leave_hive()        вылететь из улья
#  self.collect(flower)     (сборщик) собирать нектар с цветка
#  self.unload()            (сборщик, в улье) выгрузить нектар на склад
#  self.intercept(enemy)    (охранник) догнать врага
#  self.signal(1, 2, 3)     сказать своим рядом до 8 чисел
#  self.mark(0)             оставить запах (каналы 0–3)
#  Домашние пчёлы: self.process() — делать мёд, self.nurse() — растить
#  личинок, self.rest() — отдыхать.
#  Улей в hive_step: hive.breed("forager") — вывести пчелу за мёд.
#  Если за тик вызвать несколько команд движения — сработает последняя.
#  Если ничего не вызвать — пчела продолжит прошлую команду.
#
#  ---------------------------------------------------------------------
#  КАК ПОЛУЧАЕТСЯ МЁД
#  ---------------------------------------------------------------------
#  сборщик набирает нектар на цветке → несёт в улей → unload() →
#  домашние пчёлы process() превращают 1 нектар в 0.5 мёда.
#  Мёд тратится на заправку пчёл, еду домашних и новых пчёл.
#  Побеждает улей, у которого в конце больше мёда.
#
#  ---------------------------------------------------------------------
#  ТРИ ПОДСКАЗКИ
#  ---------------------------------------------------------------------
#  1. Следи за энергией: пчела без энергии падает и погибает.
#     if s.me.energy_percent < 30: self.go_home()
#  2. Сборщик видит недалеко. Пусть разведчики находят цветы и сообщают
#     координаты через signal(), а сборщики читают s.messages.
#  3. Не трать весь мёд на новых пчёл — домашним нужно есть, иначе они
#     перестанут делать мёд.
#
#  ---------------------------------------------------------------------
#  С ЧЕГО НАЧАТЬ
#  ---------------------------------------------------------------------
#  Ниже все классы уже есть, но их step() пока ничего своего не делает —
