#  ---------------------------------------------------------------------
#  self.pos            где я (self.pos.x, self.pos.y), метры
#  self.energy         сколько энергии осталось, 0–100 %. На нуле пчела падает!
#  self.nectar         сколько нектара несу (сборщик носит до 1.5)
#  self.is_full        True, если груз полный
#  self.at_home        True, если я дома, в улье
#  self.home           где вход в мой улей
#  self.flowers        цветы рядом. У цветка: .pos, .nectar, .distance, .spider
#  self.nearest_flower()  ближайший цветок (или None, если не видно)
#  self.bees           пчёлы рядом (.friend — своя ли)
#  self.heard          что я услышала (.word — слово, .where — место)
#  self.smell("red")   чую ли запах красного цвета
#  self.time           сколько секунд идёт матч
#  Видно только то, что близко! Разведчик видит на 25 м, сборщик — на 8 м.
#
#  ---------------------------------------------------------------------
#  КОМАНДЫ
#  ---------------------------------------------------------------------
#  self.fly_to(цель)       лететь к цветку, пчеле, месту из сообщения или (x, y)
#  self.search(цель)       лететь, но остановиться у первого цветка с нектаром
#  self.explore()          искать цветы вокруг дома; вернёт цветок или None
#  self.collect(цветок)    (сборщик) собирать нектар; True — груз полный
#  self.go_home()          домой, в улей: нектар выгрузится сам
#  self.refuel(80)         заправиться дома до 80 %
#  self.wait(2)            подождать 2 секунды
#  self.stop()             остановиться
#  self.say("flowers", flower)   сказать своим рядом слово и место
#  self.mark("red")        оставить запах
#  Улей (класс Hive): self.hatch(Collector) — вывести пчелу за мёд.
#  Домашние пчёлы (Worker) работают сами: делают мёд и растят личинки.
#
#  ---------------------------------------------------------------------
#  КАК ПОЛУЧАЕТСЯ МЁД
#  ---------------------------------------------------------------------
#  сборщик набирает нектар на цветке → несёт в улей (go_home) →
#  домашние пчёлы сами превращают 1 нектар в 0.5 мёда.
#  Мёд тратится на заправку пчёл, еду домашних и новых пчёл.
#  Побеждает улей, у которого в конце больше мёда.
#
#  ---------------------------------------------------------------------
#  ТРИ ПОДСКАЗКИ
#  ---------------------------------------------------------------------
#  1. Когда энергии меньше 30 %, пчела сама летит домой заправляться.
#     Улей может поменять порог: self.set_home_energy(40).
#  2. Сборщик видит недалеко. Пусть разведчики находят цветы и говорят
#     say("flowers", flower), а сборщики слушают self.heard.
#  3. Не трать весь мёд на новых пчёл — домашним нужно есть, иначе они
#     перестанут делать мёд. Новые домашние: self.hatch(Worker).
